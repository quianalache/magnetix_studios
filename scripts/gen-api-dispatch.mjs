#!/usr/bin/env node
/**
 * Consolidated API route groups — generator + guard (Vercel route-limit fix,
 * 2026-09-29). See src/lib/server/api-dispatch.ts for the why.
 *
 * Each GROUP below is served by ONE generated optional catch-all route,
 * `<group>/[[...path]]/route.ts`, that dispatches to the group's original
 * handler modules in `<group>/_routes/<same sub-path>/route.ts` (a private
 * folder: Next never routes it). URLs, methods, params and handler code are
 * unchanged.
 *
 *   node scripts/gen-api-dispatch.mjs --move    one-time: git mv a group's route.ts files into _routes/
 *   node scripts/gen-api-dispatch.mjs --write   regenerate every [[...path]]/route.ts
 *   node scripts/gen-api-dispatch.mjs --check   fail if anything is out of sync (runs in `pnpm lint`)
 *
 * Adding an endpoint to a consolidated group: create
 * `<group>/_routes/<sub-path>/route.ts` exactly like a normal route file,
 * then run `--write`. A handler that needs its own route-segment config
 * (maxDuration, runtime other than nodejs, revalidate, …) must stay a real
 * route file OUTSIDE `_routes`, and its first segment below the group must be
 * static (Next forbids a dynamic sibling of `[[...path]]`).
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");

export const GROUPS = [
  "src/app/api/community/[saId]/[groupId]",
  "src/app/api/sub-accounts/[id]/energetic-decoder",
  "src/app/api/sub-accounts/[id]/ytcs",
  "src/app/api/portal/[saId]",
  "src/app/api/sub-accounts/[id]/growth",
  "src/app/api/sub-accounts/[id]/standalone-courses",
  "src/app/api/agency/standalone-courses",
  "src/app/api/sub-accounts/[id]/projects",
  "src/app/api/sub-accounts/[id]/media-library",
  "src/app/api/sub-accounts/[id]/routines",
];

const DISPATCH_DIR = "[[...path]]";
const HANDLERS_DIR = "_routes";
// Route-segment config a handler may carry and still be consolidated (the
// dispatcher sets exactly these). Anything else keeps the handler standalone.
const ALLOWED_CONFIG = [
  /^export const dynamic = ["']force-dynamic["'];?$/,
  /^export const runtime = ["']nodejs["'];?$/,
];
const CONFIG_EXPORT = /^export (const|let|var) (dynamic|dynamicParams|revalidate|fetchCache|runtime|preferredRegion|maxDuration)\b/;

const rel = (p) => path.relative(ROOT, p).split(path.sep).join("/");

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p, out);
    else if (e.name === "route.ts" || e.name === "route.tsx") out.push(p);
  }
  return out;
}

function configIssues(file) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  return lines.filter((l) => CONFIG_EXPORT.test(l.trim()) && !ALLOWED_CONFIG.some((re) => re.test(l.trim())));
}

function relativeImports(file) {
  return (fs.readFileSync(file, "utf8").match(/from\s+["']\.\.?\/[^"']*["']/g) ?? []);
}

/** Standalone (kept) route files inside a group, outside _routes/ and the dispatcher. */
function standaloneRoutes(groupAbs) {
  return walk(groupAbs).filter((f) => {
    const r = path.relative(groupAbs, f).split(path.sep);
    return r[0] !== HANDLERS_DIR && r[0] !== DISPATCH_DIR;
  });
}

function move() {
  for (const group of GROUPS) {
    const abs = path.join(ROOT, group);
    for (const file of standaloneRoutes(abs)) {
      if (configIssues(file).length) {
        console.log(`keep  ${rel(file)}  (${configIssues(file).join(" ")})`);
        continue;
      }
      if (relativeImports(file).length) throw new Error(`relative import in ${rel(file)} — fix before moving`);
      const sub = path.relative(abs, file);
      const dest = path.join(abs, HANDLERS_DIR, sub);
      fs.mkdirSync(path.dirname(dest), { recursive: true });
      execFileSync("git", ["mv", file, dest], { cwd: ROOT });
      console.log(`move  ${rel(file)}`);
    }
  }
}

function patternOf(groupAbs, file) {
  const dir = path.dirname(path.relative(path.join(groupAbs, HANDLERS_DIR), file));
  return dir === "." ? "" : dir.split(path.sep).join("/");
}

function render(group) {
  const abs = path.join(ROOT, group);
  const handlers = walk(path.join(abs, HANDLERS_DIR)).sort();
  const alias = (f) => "@/" + rel(f).replace(/^src\//, "").replace(/\.tsx?$/, "");
  const imports = handlers.map((f, i) => `import * as h${i} from "${alias(f)}";`);
  const table = handlers.map((f, i) => `  [${JSON.stringify(patternOf(abs, f))}, h${i}],`);
  return `// GENERATED by scripts/gen-api-dispatch.mjs — do not edit. Run \`node scripts/gen-api-dispatch.mjs --write\`.
// One route for every endpoint under ${group.replace(/^src\/app/, "")}; handlers live in ../${HANDLERS_DIR}/.
import "server-only";

import { createApiDispatcher } from "@/lib/server/api-dispatch";
${imports.join("\n")}

export const dynamic = "force-dynamic";
export const runtime = "nodejs";

const d = createApiDispatcher([
${table.join("\n")}
]);

export const GET = d.GET;
export const HEAD = d.HEAD;
export const POST = d.POST;
export const PUT = d.PUT;
export const PATCH = d.PATCH;
export const DELETE = d.DELETE;
export const OPTIONS = d.OPTIONS;
`;
}

function problems() {
  const out = [];
  for (const group of GROUPS) {
    const abs = path.join(ROOT, group);
    const handlers = walk(path.join(abs, HANDLERS_DIR));
    if (!handlers.length) out.push(`${group}: no handlers in ${HANDLERS_DIR}/`);
    for (const f of handlers) {
      const bad = configIssues(f);
      if (bad.length) out.push(`${rel(f)}: route config ${bad.join(" ")} — keep it standalone outside ${HANDLERS_DIR}/`);
      if (relativeImports(f).length) out.push(`${rel(f)}: relative import (use @/ paths)`);
    }
    for (const f of standaloneRoutes(abs)) {
      const first = path.relative(abs, f).split(path.sep)[0];
      if (first === "route.ts" || /^\[/.test(first)) {
        out.push(`${rel(f)}: conflicts with ${DISPATCH_DIR} — move it into ${HANDLERS_DIR}/ (or give it a static first segment)`);
      } else if (!configIssues(f).length) {
        out.push(`${rel(f)}: plain route outside ${HANDLERS_DIR}/ — move it in so it doesn't cost 3 Vercel routes`);
      }
    }
    const file = path.join(abs, DISPATCH_DIR, "route.ts");
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== render(group)) {
      out.push(`${rel(file)}: out of date — run node scripts/gen-api-dispatch.mjs --write`);
    }
  }
  return out;
}

const isCli = process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href;
const mode = isCli ? process.argv[2] : null;
if (!isCli) {
  // Imported (e.g. by scripts/check-api-dispatch.ts) for GROUPS only.
} else if (mode === "--move") {
  move();
} else if (mode === "--write") {
  for (const group of GROUPS) {
    const file = path.join(ROOT, group, DISPATCH_DIR, "route.ts");
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, render(group));
    console.log(`wrote ${rel(file)}`);
  }
} else if (mode === "--check") {
  const p = problems();
  if (p.length) {
    console.error(`✗ API dispatch groups out of sync:\n  ${p.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`✓ API dispatch check passed — ${GROUPS.length} consolidated groups in sync.`);
} else {
  console.error("usage: node scripts/gen-api-dispatch.mjs --move | --write | --check");
  process.exit(2);
}
